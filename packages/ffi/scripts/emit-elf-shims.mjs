// Emits elf/shims.d.ts — the ambient signature-only `echo_*` declarations
// extracted from src/internal/ffi.ts. scriptc's --ffi needs these in the
// CONSUMER's program to resolve the raw shim calls in the shipped dist JS.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../src/internal/ffi.ts", import.meta.url), "utf8");
const decls = src.match(/(?:export )?declare function echo_\w+\s*\([^;]*\)[^;{]*;/gs);
if (decls === null || decls.length === 0) {
  throw new Error("no echo_* declarations found in src/internal/ffi.ts");
}
const body = decls.map((d) => d.replace(/\s+/g, " ").trim()).join("\n");
mkdirSync(new URL("../elf", import.meta.url), { recursive: true });
writeFileSync(
  new URL("../elf/shims.d.ts", import.meta.url),
  "// Ambient signature-only bindings for the @cutils/ffi echo shim. Copy this\n" +
    "// file beside your entry point and reference it so scriptc --ffi can\n" +
    "// resolve the echo_* calls in the package's shipped JS:\n" +
    '//   /// <reference path="./shims.d.ts" />\n' +
    "// Generated by scripts/emit-elf-shims.mjs from src/internal/ffi.ts —\n" +
    "// do not edit by hand.\n" +
    body +
    "\n",
);
console.log(`wrote elf/shims.d.ts (${decls.length} declarations)`);
